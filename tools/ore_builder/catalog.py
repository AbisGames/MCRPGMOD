"""Every ore in the mod: tier, form, use, where it spawns and its colour.

Sources: the design document "Fantastik Cevherler - Kademe, Nadirlik ve Setler" (tiers T1-T9, sets and special uses),
plus the 27 regional ores of the worldgen branch, sorted into the same tiers (common -> T1, uncommon -> T2,
rare -> T3, epic -> T5). Duplicates are merged (Kan Tasi = bloodstone, Gunes Tasi = sunstone). The Mistborn base
metals that have no vanilla ore (tin, zinc, cadmium, chromium, nickel, aluminum) are ores too, so they can be ground
into flakes later.

Fields of an entry:
  id     registry name
  en/tr  display name in English / Turkish
  tier   1-9
  form   'metal' (raw item, smelts to an ingot) or 'gem' (drops the gem itself)
  use    'set' (armor + tools + weapons), 'special' (its own use), 'alloy' (crafted, not mined),
         'relic' (found, not mined), 'limited' (a fixed number per world), 'mistborn' (an Allomancy metal)
  place  where it spawns (see PLACES), or None when it isn't generated as an ore
  color  RGB the textures are tinted with
  note   the use, in English (item tooltip)
"""

